"""Metric dictionary (Run 6, 60.1): one source of truth for what every
reader-facing metric measures.

Each entry states the formula, units, denominator, price basis, what is
included and excluded, and whether the inputs are actual, allocated or
estimated. Three surfaces read this module so they can never drift apart:

- ``docs/metric-dictionary.md`` is generated by ``render_metric_dictionary``
  and a test asserts the committed file matches, byte for byte.
- The central label dictionary (``margin_engine.labels``) merges
  ``metric_label_entries``, so the web bundle and the HTML report serve these
  definitions through the same path as every other label.
- UI tooltips look the entries up from the bundle's label dictionary.

Entries describe what the engine computes TODAY. Where a later Run 6 phase
changes a formula, the pending change is recorded in ``pending_note`` (shown
in the generated document, never in a tooltip) and the entry is updated in
the phase that lands the change — a tooltip must never describe code that
does not exist yet.
"""

